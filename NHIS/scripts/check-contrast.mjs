// Verifies NHIS colour pairs against their targets and writes validation/contrast-report.md.
// Fails (exit 1) if any required pair is below target. Ratios are not rounded before comparison (NHIS A19).
// Usage: npm run check:contrast
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ROOT, loadSource, flatten, resolveAll, contrast, hasAlpha } from './lib/tokens.mjs';

const resolved = resolveAll(flatten(loadSource()));
const get = (p) => {
  const t = resolved.get(p);
  if (!t) throw new Error(`Unknown token ${p}`);
  return t.resolved;
};

const SURFACES = ['color.surface.canvas', 'color.surface.panel', 'color.surface.raised', 'color.surface.overlay'];
const TINTS = ['advisory', 'caution', 'warning', 'emergency'].map((p) => `color.status.${p}.tint`).concat('color.mode.simulation.tint');

/** [foreground, background, target, rule] */
const pairs = [];
const add = (fg, bgs, target, rule) => bgs.forEach((bg) => pairs.push([fg, bg, target, rule]));

// Text
add('color.text.primary', SURFACES, 10, 'NHIS A19 — telemetry and alert text toward NASA preferred 10:1');
add('color.text.secondary', SURFACES, 6, 'NHIS A19 — NASA 6:1 minimum');
add('color.text.muted', SURFACES, 6, 'NHIS A19 — NASA 6:1 minimum (metadata)');
add('color.text.primary', TINTS, 10, 'NHIS A19 — alert text on alert tint');
add('color.text.secondary', TINTS, 6, 'NHIS A19 — supporting text on alert tint');
for (const p of ['advisory', 'warning', 'emergency']) add(`color.status.${p}.onFill`, [`color.status.${p}.fill`], 6, 'NHIS A19 — alert label on alert fill');
add('color.status.caution.onFill', ['color.status.caution.fill'], 6, 'NHIS A19 — alert label on Caution fill');
add('color.mode.simulation.onFill', ['color.mode.simulation.fill'], 6, 'NHIS A9/A19 — mode label on mode fill');
add('color.interactive.primary.text', ['color.interactive.primary.background', 'color.interactive.primary.backgroundHover', 'color.interactive.primary.backgroundPressed'], 10, 'NHIS A19 — action labels');
add('color.interactive.secondary.text', ['color.interactive.secondary.background', 'color.interactive.secondary.backgroundHover', 'color.interactive.secondary.backgroundPressed'], 10, 'NHIS A19 — action labels');
add('color.interactive.quiet.text', ['color.surface.panel', 'color.interactive.quiet.backgroundHover', 'color.interactive.quiet.backgroundPressed'], 10, 'NHIS A19 — action labels');
add('color.text.primary', ['color.interactive.selected.background'], 10, 'NHIS A19 — selected item text');
add('color.viz.axis', ['color.surface.panel', 'color.surface.raised'], 6, 'NHIS A19 — chart text');

// Non-text (3:1)
add('color.border.control', ['color.surface.panel', 'color.surface.raised'], 3, 'NHIS A20 / WCAG 1.4.11 — control boundary');
add('color.border.focus', SURFACES, 3, 'NHIS A20 / WCAG 2.4.11 — focus indicator');
add('color.border.focus', ['color.border.focusHalo'], 3, 'Focus ring against its own halo');
for (const p of ['advisory', 'caution', 'warning', 'emergency']) add(`color.status.${p}.stroke`, SURFACES, 3, 'NHIS A20 — alert shape/stroke');
add('color.mode.simulation.stroke', SURFACES, 3, 'NHIS A9/A20 — mode frame');
add('color.data.degradedStroke', SURFACES, 3, 'NHIS A7/A20 — degraded-data outline');
add('color.interactive.selected.indicator', ['color.surface.panel', 'color.surface.raised'], 3, 'NHIS A20 — selected indicator');
add('color.viz.live', ['color.surface.panel', 'color.surface.raised'], 3, 'NHIS A20 — chart line');
add('color.viz.historical', ['color.surface.panel', 'color.surface.raised'], 3, 'NHIS A20 — chart line');
add('color.viz.baselineEdge', ['color.surface.panel', 'color.surface.raised', 'color.viz.baselineBand'], 3, 'NHIS A20 — baseline band edge');
add('color.viz.limitCaution', ['color.surface.panel'], 3, 'NHIS A20/A25 — limit line');
add('color.viz.limitWarning', ['color.surface.panel'], 3, 'NHIS A20/A25 — limit line');
add('color.hazard.stripeLight', ['color.hazard.stripeDark'], 3, 'NHIS A10 — hazard striping');

const rows = [];
let failures = 0;
for (const [fg, bg, target, rule] of pairs) {
  const a = get(fg);
  const b = get(bg);
  if (hasAlpha(a) || hasAlpha(b)) continue;
  const ratio = contrast(a, b);
  const pass = ratio >= target;
  if (!pass) failures++;
  rows.push(`| \`${fg}\` | \`${bg}\` | ${a} / ${b} | ${ratio.toFixed(2)}:1 | ${target}:1 | ${pass ? 'Pass' : '**FAIL**'} | ${rule} |`);
}

// Informational: grayscale separation of alert fills (A2 requires a second cue regardless).
const fills = ['advisory', 'caution', 'warning'].map((p) => [p, get(`color.status.${p}.fill`)]);
const gray = fills.map(([p, hex]) => `| ${p} | ${hex} | ${contrast(hex, '#000000').toFixed(2)} |`);

const report = `# NHIS contrast report

Generated by \`scripts/check-contrast.mjs\` from \`tokens/source/tokens.json\`. Do not edit by hand.

- WCAG 2.x relative-luminance contrast, computed on resolved token values and **not rounded** before comparison (NHIS A19).
- Targets: text 6:1 minimum (NASA App. F), telemetry and alert text 10:1 (NASA preferred), non-text 3:1 (WCAG 1.4.11, NHIS A20).
- Scope: Station dark theme on a laptop display. This does **not** validate EVA see-through legibility; no source states a required see-through contrast ratio (NHIS B24, U). See \`validation/unresolved-decisions.md\`.
- Translucent tokens (\`surface.scrim\`, \`eva.plate\`) are excluded because their contrast depends on what is behind them.

**Result: ${rows.length - failures} of ${rows.length} pairs pass${failures ? `, ${failures} FAIL` : ''}.**

| Foreground | Background | Values | Ratio | Target | Result | Rule |
|---|---|---|---|---|---|---|
${rows.join('\n')}

## Grayscale separation of alert fills (informational)

Alert classes are never identified by colour alone: every class carries a label, a distinct glyph shape and an IEC-style marker (NHIS A2). Luminance against black is listed so reviewers can see why grayscale review relies on those cues.

| Class | Fill | Ratio vs black |
|---|---|---|
${gray.join('\n')}
`;

writeFileSync(resolve(ROOT, 'validation/contrast-report.md'), report);
console.log(`NHIS contrast: ${rows.length - failures}/${rows.length} pairs pass → validation/contrast-report.md`);
if (failures) {
  console.error(`NHIS contrast: ${failures} pair(s) below target.`);
  process.exit(1);
}
